/** 며칠 전으로 흩어놓습니다 — 전부 같은 시각이면 정렬이 무의미해집니다. */
export function workNotes() {
  const now = Date.now();
  return NOTES.map(([sessionId, empNo, note], i) => {
    const at = new Date(now - (i * 7 + 3) * 3_600_000).toISOString();
    return {
      id: `${sessionId}_${empNo}`,
      sessionId,
      empNo,
      note,
      createdAt: at,
      updatedAt: at,
    };
  });
}
